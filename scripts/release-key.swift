// Creates the Ed25519 release-signing key pair (run once; again only to rotate).
//
//   swift scripts/release-key.swift
//
// The private key (base64 of the raw 32-byte seed) goes straight into the repository's Actions
// secret MLXRUNNER_UPDATE_KEY via `gh secret set` (stdin): it is never written to disk or printed.
// The public key is written to packaging/update-key.pub and Sources/MLXEngine/UpdateKey.swift,
// so the in-app updater only installs releases signed by the release workflow.
//
// Rotating the key means existing installs can no longer verify new releases: users update
// manually once. Don't rotate without a reason.
import CryptoKit
import Foundation

let repo = "BackendStack21/mlx-runner"
let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()

let key = Curve25519.Signing.PrivateKey()
// Fail on file-system problems before the secret is touched, so the two halves never diverge.
try FileManager.default.createDirectory(at: root.appendingPathComponent("packaging"), withIntermediateDirectories: true)
let gh = Process()
gh.executableURL = URL(fileURLWithPath: "/usr/bin/env")
gh.arguments = ["gh", "secret", "set", "MLXRUNNER_UPDATE_KEY", "--repo", repo]
let pipe = Pipe()
gh.standardInput = pipe
try gh.run()
pipe.fileHandleForWriting.write(key.rawRepresentation.base64EncodedString().data(using: .utf8)!)
try pipe.fileHandleForWriting.close()
gh.waitUntilExit()
guard gh.terminationStatus == 0 else { fatalError("gh secret set failed; nothing was written") }

// SPKI DER for Ed25519 = fixed 12-byte prefix + the 32-byte raw public key.
let spki = Data([0x30, 0x2a, 0x30, 0x05, 0x06, 0x03, 0x2b, 0x65, 0x70, 0x03, 0x21, 0x00]) + key.publicKey.rawRepresentation
let pem = "-----BEGIN PUBLIC KEY-----\n\(spki.base64EncodedString())\n-----END PUBLIC KEY-----\n"
try pem.write(to: root.appendingPathComponent("packaging/update-key.pub"), atomically: true, encoding: .utf8)
let swiftKey = """
// Generated by scripts/release-key.swift: the Ed25519 public key whose private half signs
// every release's SHA256SUMS (see Updater.swift). Do not edit by hand.
enum UpdateKey {
    static let publicKeyBase64 = "\(key.publicKey.rawRepresentation.base64EncodedString())"
}

"""
try swiftKey.write(to: root.appendingPathComponent("Sources/MLXEngine/UpdateKey.swift"), atomically: true, encoding: .utf8)
print("Stored the private key in the MLXRUNNER_UPDATE_KEY secret of \(repo); wrote packaging/update-key.pub:\n\(pem)")
